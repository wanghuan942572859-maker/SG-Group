"""
Semantic-enhanced mask association script
Entry point for semantic mask association
SG-Group combines geometry and language features for mask association.
"""

import os
import sys
import torch
from argparse import ArgumentParser

from arguments import ModelParams, PipelineParams, get_combined_args
from mask.projector_semantic import GaussianProjectorSemantic


def associate_semantic(dataset, pipeline, args):
    """
    Run semantic mask association

    Steps:
    1. Load a trained 3DGS model containing language features
    2. Load raw 2D masks generated by SAM
    3. Associate masks across views using geometry and semantic similarity
    4. Save the associated masks
    """

    print("\n" + "=" * 80)
    print("SG-Group: semantic mask association")
    print("Fusion of Geometric Overlap (IOCUR) and Semantic Similarity (CLIP)")
    print("=" * 80 + "\n")

    # Check that language features exist
    language_features_path = os.path.join(args.source_path, "language_features_dim3")
    if not os.path.isdir(language_features_path):
        raise FileNotFoundError(f"Compressed language features missing: {language_features_path}")

    # Build parameters
    params = {
        "seg_method": args.seg_method,
        "front_percentage": args.front_percentage,
        "overlap_threshold": args.overlap_threshold,
        "semantic_threshold": args.semantic_threshold,
        "semantic_weight": args.semantic_weight,
        "combined_threshold": args.combined_threshold,
        "num_patch": args.num_patch,
        "visualize": args.visualize,
        "autoencoder_path": args.autoencoder_path,
        "use_full_dim": args.use_full_dim,
        "similarity_method": args.similarity_method,
        "feature_update_alpha": args.feature_update_alpha,
    }

    print("\n[Config] Association Parameters:")
    for key, value in params.items():
        print(f"  {key}: {value}")

    # Create the semantic projector
    print("\n[Step 1/2] Loading Gaussian model and creating projector...")

    projector = GaussianProjectorSemantic(
        dataset=dataset,
        pipeline=pipeline,
        iteration=args.iteration,
        params=params,
        device=torch.device("cuda" if torch.cuda.is_available() else "cpu")
    )

    # Build mask associations
    print("\n[Step 2/2] Building mask association...")
    projector.build_mask_association()

    print("\n" + "=" * 80)
    print("Association Complete!")
    print(f"Total masks identified: {projector.get_num_mask}")
    print(f"Results saved to: {projector.associated_mask_folder}")
    print("=" * 80 + "\n")


if __name__ == "__main__":
    # Use the project's argument parser
    parser = ArgumentParser(description="Semantic-enhanced mask association")
    model = ModelParams(parser)
    pipeline = PipelineParams(parser)

    # Add extra arguments
    parser.add_argument("--iteration", default=-1, type=int,
                       help="Iteration of the Gaussian model to load")
    parser.add_argument("--seg_method", default="sam", type=str,
                       choices=["sam"], help="Segmentation method")
    parser.add_argument("--front_percentage", "-fp", type=float, default=0.2,
                       help="Percentage of front gaussians to use")
    parser.add_argument("--overlap_threshold", "-ot", type=float, default=0.1,
                       help="Geometric overlap threshold (IOCUR)")
    parser.add_argument("--num_patch", "-np", type=int, default=32,
                       help="Number of patches to divide image into")

    # Semantic arguments
    parser.add_argument("--semantic_threshold", type=float, default=0.5,
                       help="Semantic similarity threshold (cosine)")
    parser.add_argument("--semantic_weight", type=float, default=0.5,
                       help="Weight of semantic similarity (0-1)")
    parser.add_argument("--combined_threshold", type=float, default=0.2,
                       help="Combined score threshold for matching")
    parser.add_argument("--autoencoder_path", type=str, default=None,
                       help="Path to autoencoder checkpoint")
    parser.add_argument("--use_full_dim", action="store_true",
                       help="Use 512D features instead of 3D")
    parser.add_argument("--similarity_method", type=str, default="cosine",
                       choices=["cosine", "l2", "dot"],
                       help="Semantic similarity method")
    parser.add_argument("--feature_update_alpha", type=float, default=0.1,
                       help="EMA alpha for feature bank updates")
    parser.add_argument("--visualize", "-v", action="store_true",
                       help="Visualize mask association results")

    args = get_combined_args(parser)

    # Fill missing semantic arguments for older cfg_args files
    if not hasattr(args, 'semantic_threshold'):
        args.semantic_threshold = 0.5
    if not hasattr(args, 'semantic_weight'):
        args.semantic_weight = 0.5
    if not hasattr(args, 'combined_threshold'):
        args.combined_threshold = 0.2
    if not hasattr(args, 'autoencoder_path'):
        args.autoencoder_path = None
    if not hasattr(args, 'use_full_dim'):
        args.use_full_dim = False
    if not hasattr(args, 'similarity_method'):
        args.similarity_method = 'cosine'
    if not hasattr(args, 'feature_update_alpha'):
        args.feature_update_alpha = 0.1
    if not hasattr(args, 'visualize'):
        args.visualize = False

    # Run association
    with torch.no_grad():
        try:
            associate_semantic(model.extract(args), pipeline.extract(args), args)
        except KeyboardInterrupt:
            print("\n\n[Interrupted] Association interrupted by user")
            sys.exit(1)
        except Exception as e:
            print(f"\n\n[Error] Association failed: {e}")
            import traceback
            traceback.print_exc()
            sys.exit(1)
